def require_dependencies():
    if torch is None:
        raise RuntimeError(
            "PyTorch/Transformers/PEFT import failed. Install requirements first. "
            f"Original import error: {_IMPORT_ERROR}"
        )


def label_token_ids(tokenizer):
    # Prefer whitespace-prefixed single tokens because prompts end at 'Class:'.
    ids = []
    target_text = []
    for label in LABEL_NAMES:
        choices = [f" {label}", label]
        found = None
        for txt in choices:
            enc = tokenizer.encode(txt, add_special_tokens=False)
            if len(enc) == 1:
                found = (enc[0], txt)
                break
        if found is None:
            raise RuntimeError(
                f"Could not find a single-token encoding for class {label}. "
                "Try a different model/tokenizer."
            )
        ids.append(found[0])
        target_text.append(found[1])
    if len(set(ids)) != len(ids):
        raise RuntimeError(f"Class token IDs are not distinct: {ids}")
    return ids, target_text


def infer_lora_targets(model):
    leaves = {name.split(".")[-1] for name, _ in model.named_modules()}
    if {"q_proj", "v_proj"}.issubset(leaves):
        return ["q_proj", "v_proj"]
    if "c_attn" in leaves:  # GPT-2 family
        return ["c_attn"]
    if {"query", "value"}.issubset(leaves):
        return ["query", "value"]
    # Last-resort common projection names.
    candidates = [x for x in ["q_proj", "v_proj", "k_proj", "o_proj"] if x in leaves]
    if candidates:
        return candidates[:2]
    raise RuntimeError(
        "Could not infer LoRA target modules. Inspect model.named_modules() and "
        "supply a supported model."
    )


def load_model(cfg: Config, seed: int):
    set_all_seeds(seed)
    tokenizer = AutoTokenizer.from_pretrained(cfg.model_name)
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = AutoModelForCausalLM.from_pretrained(cfg.model_name)
    targets = infer_lora_targets(model)
    lcfg = LoraConfig(
        r=cfg.lora_rank,
        lora_alpha=cfg.lora_alpha,
        lora_dropout=cfg.lora_dropout,
        bias="none",
        task_type=TaskType.CAUSAL_LM,
        target_modules=targets,
    )
    model = get_peft_model(model, lcfg)
    model.to(cfg.device)
    model.train()
    return model, tokenizer, targets


def adapter_snapshot(model):
    state = get_peft_model_state_dict(model)
    return {k: v.detach().cpu().clone() for k, v in state.items()}


def restore_adapter(model, state):
    set_peft_model_state_dict(model, {k: v.to(model.device) for k, v in state.items()})


def trainable_parameter_count(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def adapter_l2(model):
    total = 0.0
    for p in model.parameters():
        if p.requires_grad:
            total += float((p.detach().float().cpu() ** 2).sum())
    return math.sqrt(total)


# ----------------------------- batching -----------------------------------


def build_batch(tokenizer, label_ids, batch, max_length, device):
    sequences = []
    labels = []
    for prompt, y, _pair in batch:
        pids = tokenizer.encode(prompt, add_special_tokens=True)
        pids = pids[-(max_length - 1):]
        seq = pids + [int(label_ids[y])]
        lab = [-100] * len(pids) + [int(label_ids[y])]
        sequences.append(seq)
        labels.append(lab)
    maxlen = max(len(s) for s in sequences)
    pad = tokenizer.pad_token_id
    input_ids = []
    attention = []
    label_mat = []
    for seq, lab in zip(sequences, labels):
        n = maxlen - len(seq)
        input_ids.append(seq + [pad] * n)
        attention.append([1] * len(seq) + [0] * n)
        label_mat.append(lab + [-100] * n)
    return {
        "input_ids": torch.tensor(input_ids, dtype=torch.long, device=device),
        "attention_mask": torch.tensor(attention, dtype=torch.long, device=device),
        "labels": torch.tensor(label_mat, dtype=torch.long, device=device),
    }


def train_steps(model, tokenizer, label_ids, dataset, steps, batch_size, lr,
                max_length, device, seed):
    if not dataset or steps <= 0:
        return 0.0
    rr = np.random.default_rng(seed)
    model.train()
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=lr)
    started = time.perf_counter()
    for _ in range(steps):
        idx = rr.integers(0, len(dataset), size=batch_size)
        batch = [dataset[int(i)] for i in idx]
        tensors = build_batch(tokenizer, label_ids, batch, max_length, device)
        out = model(**tensors)
        loss = out.loss
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_([p for p in model.parameters() if p.requires_grad], 1.0)
        opt.step()
    return time.perf_counter() - started


@torch.no_grad()
def class_probabilities(model, tokenizer, label_ids, prompts, max_length, device, batch_size=16):
    model.eval()
    all_probs = []
    for start in range(0, len(prompts), batch_size):
        chunk = prompts[start:start + batch_size]
        toks = [tokenizer.encode(p, add_special_tokens=True)[-(max_length):] for p in chunk]
        maxlen = max(len(x) for x in toks)
        pad = tokenizer.pad_token_id
        ids = [x + [pad] * (maxlen - len(x)) for x in toks]
        att = [[1] * len(x) + [0] * (maxlen - len(x)) for x in toks]
        input_ids = torch.tensor(ids, dtype=torch.long, device=device)
        attention = torch.tensor(att, dtype=torch.long, device=device)
        out = model(input_ids=input_ids, attention_mask=attention)
        lengths = attention.sum(1) - 1
        rows = torch.arange(len(chunk), device=device)
        next_logits = out.logits[rows, lengths]
        class_logits = next_logits[:, torch.tensor(label_ids, device=device)]
        probs = torch.softmax(class_logits.float(), dim=-1)
        all_probs.append(probs.cpu())
    return torch.cat(all_probs, dim=0).numpy()


def ece_score(probs, y, bins=10):
    probs = np.asarray(probs)
    y = np.asarray(y)
    pred = probs.argmax(1)
    conf = probs.max(1)
    correct = (pred == y).astype(float)
    ece = 0.0
    edges = np.linspace(0, 1, bins + 1)
    for lo, hi in zip(edges[:-1], edges[1:]):
        mask = (conf >= lo) & (conf < hi if hi < 1 else conf <= hi)
        if mask.any():
            ece += mask.mean() * abs(correct[mask].mean() - conf[mask].mean())
    return float(ece)


def evaluate(model, tokenizer, label_ids, dataset, cfg):
    prompts = [x[0] for x in dataset]
    y = np.array([x[1] for x in dataset], dtype=int)
    probs = class_probabilities(model, tokenizer, label_ids, prompts,
                                cfg.max_length, cfg.device, cfg.batch_size * 2)
    pred = probs.argmax(1)
    acc = float((pred == y).mean()) if len(y) else float("nan")
    nll = float(-np.log(np.clip(probs[np.arange(len(y)), y], 1e-9, 1)).mean()) if len(y) else float("nan")
    return {
        "accuracy": acc,
        "nll": nll,
        "ece": ece_score(probs, y) if len(y) else float("nan"),
        "mean_confidence": float(probs.max(1).mean()) if len(y) else float("nan"),
    }


# ---------------------- endogenous data generation ------------------------


def sample_from_probs(probs, k, temperature, rr):
    p = np.asarray(probs, float)
    logits = np.log(np.clip(p, 1e-12, 1)) / max(temperature, 1e-6)
    q = np.exp(logits - logits.max())
    q /= q.sum()
    return rr.choice(len(q), size=k, replace=True, p=q)


def make_unchecked_dataset(model, tokenizer, label_ids, pool_examples, cfg, seed):
    rr = np.random.default_rng(seed)
    chosen = pool_examples.copy()
    rr.shuffle(chosen)
    chosen = chosen[:cfg.internal_prompt_budget]
    probs = class_probabilities(model, tokenizer, label_ids, [e[0] for e in chosen],
                                cfg.max_length, cfg.device, cfg.batch_size * 2)
    out = []
    wrong = 0
    for e, p in zip(chosen, probs):
        candidates = sample_from_probs(p, cfg.candidate_samples, cfg.temperature, rr)
        # No verifier: choose the most frequent internally sampled class, tie broken by model probability.
        counts = np.bincount(candidates, minlength=cfg.n_classes)
        best = np.flatnonzero(counts == counts.max())
        yhat = int(best[np.argmax(p[best])])
        if yhat != e[1]:
            wrong += 1
        out.append((e[0], yhat, e[2]))
    return out, {
        "generated_prompts": len(chosen),
        "accepted": len(out),
        "acceptance_rate": 1.0,
        "pseudo_label_error_rate": wrong / max(1, len(out)),
    }


def validated_dataset(model, tokenizer, label_ids, pool_examples, cfg, seed,
                      hard=False):
    rr = np.random.default_rng(seed)
    pool = pool_examples.copy()
    if hard:
        score_n = min(len(pool), cfg.internal_prompt_budget * cfg.hard_pool_multiplier)
        rr.shuffle(pool)
        candidate_pool = pool[:score_n]
        probs0 = class_probabilities(model, tokenizer, label_ids, [e[0] for e in candidate_pool],
                                     cfg.max_length, cfg.device, cfg.batch_size * 2)
        entropy = -(probs0 * np.log(np.clip(probs0, 1e-12, 1))).sum(1)
        order = np.argsort(-entropy)
        chosen = [candidate_pool[int(i)] for i in order[:cfg.internal_prompt_budget]]
        probs = probs0[order[:cfg.internal_prompt_budget]]
    else:
        rr.shuffle(pool)
        chosen = pool[:cfg.internal_prompt_budget]
        probs = class_probabilities(model, tokenizer, label_ids, [e[0] for e in chosen],
                                    cfg.max_length, cfg.device, cfg.batch_size * 2)

    accepted = []
    attempts = 0
    for e, p in zip(chosen, probs):
        candidates = sample_from_probs(p, cfg.candidate_samples, cfg.temperature, rr)
        attempts += len(candidates)
        # Executable verifier returns pass/fail. It does NOT supply a corrected label if all candidates fail.
        good = [int(c) for c in candidates if int(c) == int(e[1])]
        if good:
            accepted.append((e[0], good[0], e[2]))
    return accepted, {
        "generated_prompts": len(chosen),
        "candidate_attempts": attempts,
        "accepted": len(accepted),
        "acceptance_rate": len(accepted) / max(1, len(chosen)),
        "pseudo_label_error_rate": 0.0,
    }


def mix_anchor(endogenous, anchors, fraction, total_size, seed):
    rr = np.random.default_rng(seed)
    n_anchor = int(round(total_size * fraction))
    n_endo = max(0, total_size - n_anchor)
    out = []
    if endogenous:
        out.extend([endogenous[int(i)] for i in rr.integers(0, len(endogenous), size=n_endo)])
    if anchors:
        out.extend([anchors[int(i)] for i in rr.integers(0, len(anchors), size=n_anchor)])
    rr.shuffle(out)
    return out


# ---------------------------- one seed ------------------------------------

CONDITIONS = [
    "no_update",
    "replay",
    "unchecked",
    "validated",
    "hard_validated",
    "dream_validated",
    "hard_validated_anchor",
]


def run_seed(seed: int, cfg: Config):
    require_dependencies()
    set_all_seeds(seed)
    rr = np.random.default_rng(seed)
    splits = split_pairs(seed, cfg)
    target_rule = rule_params(rr)
    anchor_rule = rule_params(rr)
    while anchor_rule == target_rule:
        anchor_rule = rule_params(rr)

    target_exp = examples("ZORP", splits["target_exposure"], target_rule, cfg.n_classes)
    target_eval_all = examples("ZORP", splits["target_eval_all"], target_rule, cfg.n_classes)
    target_eval_cross = examples("ZORP", splits["target_eval_cross"], target_rule, cfg.n_classes)
    target_eval_same = examples("ZORP", splits["target_eval_same"], target_rule, cfg.n_classes)
    uniform_pool = examples("ZORP", splits["internal_uniform"], target_rule, cfg.n_classes)
    dream_pool = examples("ZORP", splits["dream_cross"], target_rule, cfg.n_classes)
    anchor_exp = examples("MIRA", splits["anchor_exposure"], anchor_rule, cfg.n_classes)
    anchor_eval = examples("MIRA", splits["anchor_eval"], anchor_rule, cfg.n_classes)

    model, tokenizer, targets = load_model(cfg, seed)
    label_ids, label_text = label_token_ids(tokenizer)

    # Initial external-observation phase. This is the only phase that receives externally stored labels.
    initial_data = target_exp + anchor_exp
    initial_seconds = train_steps(
        model, tokenizer, label_ids, initial_data, cfg.initial_steps, cfg.batch_size,
        cfg.learning_rate_initial, cfg.max_length, cfg.device, seed + 1
    )
    init_state = adapter_snapshot(model)
    baseline_target = evaluate(model, tokenizer, label_ids, target_eval_all, cfg)
    baseline_cross = evaluate(model, tokenizer, label_ids, target_eval_cross, cfg)
    baseline_same = evaluate(model, tokenizer, label_ids, target_eval_same, cfg)
    baseline_anchor = evaluate(model, tokenizer, label_ids, anchor_eval, cfg)

    # Freeze endogenous datasets from exactly the same post-exposure model state.
    unchecked_data, unchecked_meta = make_unchecked_dataset(
        model, tokenizer, label_ids, uniform_pool, cfg, seed + 11
    )
    validated_data, validated_meta = validated_dataset(
        model, tokenizer, label_ids, uniform_pool, cfg, seed + 12, hard=False
    )
    hard_data, hard_meta = validated_dataset(
        model, tokenizer, label_ids, uniform_pool, cfg, seed + 13, hard=True
    )
    dream_data, dream_meta = validated_dataset(
        model, tokenizer, label_ids, dream_pool, cfg, seed + 14, hard=False
    )

    generation_meta = {
        "unchecked": unchecked_meta,
        "validated": validated_meta,
        "hard_validated": hard_meta,
        "dream_validated": dream_meta,
    }

    rows = []
    for cidx, condition in enumerate(CONDITIONS):
        restore_adapter(model, init_state)
        adapt_seconds = 0.0
        train_data = []
        meta = {"generated_prompts": 0, "accepted": 0, "acceptance_rate": 0.0,
                "pseudo_label_error_rate": 0.0}

        if condition == "no_update":
            pass
        elif condition == "replay":
            train_data = target_exp
            meta = {"generated_prompts": len(target_exp), "accepted": len(target_exp),
                    "acceptance_rate": 1.0, "pseudo_label_error_rate": 0.0}
        elif condition == "unchecked":
            train_data = unchecked_data
            meta = unchecked_meta
        elif condition == "validated":
            train_data = validated_data
            meta = validated_meta
        elif condition == "hard_validated":
            train_data = hard_data
            meta = hard_meta
        elif condition == "dream_validated":
            train_data = dream_data
            meta = dream_meta
        elif condition == "hard_validated_anchor":
            # Same hard endogenous examples as hard_validated; only consolidation mix differs.
            total = max(cfg.batch_size, max(1, len(hard_data)))
            train_data = mix_anchor(hard_data, anchor_exp, cfg.anchor_fraction,
                                    total, seed + 900)
            meta = dict(hard_meta)
        else:
            raise ValueError(condition)

        if condition != "no_update" and train_data:
            adapt_seconds = train_steps(
                model, tokenizer, label_ids, train_data, cfg.adapt_steps, cfg.batch_size,
                cfg.learning_rate_adapt, cfg.max_length, cfg.device,
                seed + 1000 + cidx
            )

        m_all = evaluate(model, tokenizer, label_ids, target_eval_all, cfg)
        m_cross = evaluate(model, tokenizer, label_ids, target_eval_cross, cfg)
        m_same = evaluate(model, tokenizer, label_ids, target_eval_same, cfg)
        m_anchor = evaluate(model, tokenizer, label_ids, anchor_eval, cfg)

        rows.append({
            "seed": seed,
            "condition": condition,
            "model_name": cfg.model_name,
            "target_rule": str(target_rule),
            "anchor_rule": str(anchor_rule),
            "target_accuracy": m_all["accuracy"],
            "target_cross_accuracy": m_cross["accuracy"],
            "target_same_accuracy": m_same["accuracy"],
            "target_nll": m_all["nll"],
            "target_ece": m_all["ece"],
            "target_confidence": m_all["mean_confidence"],
            "anchor_accuracy": m_anchor["accuracy"],
            "anchor_nll": m_anchor["nll"],
            "baseline_target_accuracy": baseline_target["accuracy"],
            "baseline_cross_accuracy": baseline_cross["accuracy"],
            "baseline_same_accuracy": baseline_same["accuracy"],
            "baseline_anchor_accuracy": baseline_anchor["accuracy"],
            "generated_prompts": int(meta.get("generated_prompts", 0)),
            "candidate_attempts": int(meta.get("candidate_attempts", 0)),
            "accepted": int(meta.get("accepted", 0)),
            "acceptance_rate": float(meta.get("acceptance_rate", 0.0)),
            "pseudo_label_error_rate": float(meta.get("pseudo_label_error_rate", 0.0)),
            "initial_train_seconds": initial_seconds,
            "adapt_seconds": adapt_seconds,
            "adapter_l2": adapter_l2(model),
            "trainable_parameters": trainable_parameter_count(model),
            "lora_targets": ",".join(targets),
            "label_tokens": json.dumps(label_text),
        })

    # Free large objects between seeds.
    del model
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return rows


# --------------------------- hypothesis tests ------------------------------

PRIMARY = [
    # name, treatment, control, metric, interpretation
    ("R1_validated_gt_replay", "validated", "replay", "target_accuracy",
     "Validated endogenous adaptation improves held-out target accuracy beyond literal replay."),
    ("R2_validated_gt_unchecked", "validated", "unchecked", "target_accuracy",
     "Executable validation improves endogenous adaptation over unchecked self-training."),
    ("R3_hard_gt_uniform", "hard_validated", "validated", "target_accuracy",
     "Uncertainty-targeted endogenous practice improves held-out accuracy over uniform validated practice."),
    ("R4_dream_gt_replay_cross", "dream_validated", "replay", "target_cross_accuracy",
     "Validated cross-context recombination improves withheld cross-context accuracy over replay."),
    ("R5_anchor_preservation", "hard_validated_anchor", "hard_validated", "anchor_accuracy",
     "Anchor replay preserves prior-task accuracy during endogenous adaptation."),
]


def hypothesis_table(df: pd.DataFrame):
    rows = []
    for name, treat, control, metric, claim in PRIMARY:
        pivot = df.pivot(index="seed", columns="condition", values=metric)
        a = pivot[treat].to_numpy()
        b = pivot[control].to_numpy()
        st = paired_stats(a, b, "greater")
        rows.append({
            "hypothesis": name,
            "claim": claim,
            "metric": metric,
            "treatment_condition": treat,
            "control_condition": control,
            "treatment_mean": float(np.mean(a)),
            "control_mean": float(np.mean(b)),
            **st,
        })
    out = pd.DataFrame(rows)
    out["holm_p"] = holm_adjust(out["p_one_sided"].to_numpy())
    out["reject_h0_0.05"] = out["holm_p"] < .05
    return out


