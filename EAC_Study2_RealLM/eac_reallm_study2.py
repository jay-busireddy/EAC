    ax.set_xticklabels(order, rotation=35, ha="right")
    ax.set_ylabel("Anchor-task accuracy")
    ax.set_title("Prior-task retention by condition")
    fig.tight_layout()
    fig.savefig(os.path.join(pdir, "03_anchor_retention.png"), dpi=180)
    plt.close(fig)

