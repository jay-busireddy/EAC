    ax.axvline(0, linewidth=1)
    ax.set_yticks(y)
    ax.set_yticklabels(tests["hypothesis"])
    ax.set_xlabel("Treatment - control")
    ax.set_title("Primary paired effects with 95% confidence intervals")
    fig.tight_layout()
    fig.savefig(os.path.join(pdir, "02_primary_effects_95ci.png"), dpi=180)
    plt.close(fig)

    anchor = df.groupby("condition")["anchor_accuracy"].mean().reindex(order)
    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.bar(np.arange(len(order)), anchor.values)
