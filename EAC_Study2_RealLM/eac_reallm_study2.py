def run(cfg: Config, output: str):
    require_dependencies()
    os.makedirs(output, exist_ok=True)
    if cfg.torch_threads and cfg.torch_threads > 0:
        torch.set_num_threads(cfg.torch_threads)
    with open(os.path.join(output, "run_config.json"), "w", encoding="utf-8") as f:
        json.dump(asdict(cfg), f, indent=2)

    all_rows = []
    seeds = [cfg.base_seed + cfg.seed_stride * i for i in range(cfg.seeds)]
    for i, seed in enumerate(seeds, start=1):
        print(f"[{i}/{len(seeds)}] seed={seed} model={cfg.model_name}", flush=True)
        rows = run_seed(seed, cfg)
        all_rows.extend(rows)
        pd.DataFrame(all_rows).to_csv(os.path.join(output, "metrics_partial.csv"), index=False)

    df = pd.DataFrame(all_rows)
    df.to_csv(os.path.join(output, "metrics.csv"), index=False)
    tests = hypothesis_table(df)
    tests.to_csv(os.path.join(output, "hypothesis_tests.csv"), index=False)
    make_plots(df, tests, output)
    write_summary(df, tests, cfg, output)
    print("Done. Results written to", output)


