        x = np.arange(len(pivot))
        fig, ax = plt.subplots(figsize=(8.5, 4.7))
        ax.plot(x, pivot[treat].to_numpy(), marker="o", label=treat)
        ax.plot(x, pivot[control].to_numpy(), marker="o", label=control)
        ax.set_xlabel("Matched seed index")
