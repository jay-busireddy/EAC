# -------------------------- deterministic task ----------------------------

LABEL_NAMES = ["A", "B", "C", "D"]


def set_all_seeds(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    if torch is not None:
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)


def rule_params(rng: np.random.Generator):
    # Coefficients are intentionally small and nonzero. The task name is arbitrary,
    # so pretraining cannot know the per-seed mapping in advance.
    a = int(rng.choice([1, 2, 3]))
    b = int(rng.choice([1, 2, 3]))
    c = int(rng.integers(0, 4))
    return (a, b, c)


def apply_rule(pair: Tuple[int, int], params: Tuple[int, int, int], n_classes=4):
    x, y = pair
    a, b, c = params
    return int((a * x + b * y + c) % n_classes)


def same_context(pair: Tuple[int, int], domain_n: int):
    x, y = pair
    half = domain_n // 2
    return (x < half and y < half) or (x >= half and y >= half)


def split_pairs(seed: int, cfg: Config):
    rr = np.random.default_rng(seed)
    all_pairs = [(i, j) for i in range(cfg.domain_n) for j in range(cfg.domain_n)]
    same = [p for p in all_pairs if same_context(p, cfg.domain_n)]
    cross = [p for p in all_pairs if not same_context(p, cfg.domain_n)]
    rr.shuffle(same)
    rr.shuffle(cross)

    target_exposure = same[:cfg.target_exposure_n]
    same_rest = same[cfg.target_exposure_n:]
    target_eval_same = same_rest[:cfg.target_eval_same_n]
    same_rest = same_rest[cfg.target_eval_same_n:]
    target_eval_cross = cross[:cfg.target_eval_cross_n]
    cross_rest = cross[cfg.target_eval_cross_n:]

    eval_set = set(target_eval_same + target_eval_cross)
    exposure_set = set(target_exposure)
    internal_uniform = [p for p in all_pairs if p not in eval_set and p not in exposure_set]
    rr.shuffle(internal_uniform)
    dream_cross = [p for p in cross_rest if p not in exposure_set]
    rr.shuffle(dream_cross)

    anchor_all = all_pairs.copy()
    rr.shuffle(anchor_all)
    anchor_exposure = anchor_all[:cfg.anchor_exposure_n]
    anchor_eval = anchor_all[cfg.anchor_exposure_n:cfg.anchor_exposure_n + cfg.anchor_eval_n]

    return {
        "target_exposure": target_exposure,
        "target_eval_same": target_eval_same,
        "target_eval_cross": target_eval_cross,
        "target_eval_all": target_eval_same + target_eval_cross,
        "internal_uniform": internal_uniform,
        "dream_cross": dream_cross,
        "anchor_exposure": anchor_exposure,
        "anchor_eval": anchor_eval,
    }


def make_prompt(task: str, pair: Tuple[int, int]):
    x, y = pair
    return (
        f"Hidden-rule task {task}. first={x}; second={y}. "
        "Return exactly one class label from A, B, C, or D. Class:"
    )


def examples(task: str, pairs, params, n_classes=4):
    return [(make_prompt(task, p), apply_rule(p, params, n_classes), p) for p in pairs]


