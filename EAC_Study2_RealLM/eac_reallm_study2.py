def holm_adjust(pvals):
    pvals = np.asarray(pvals, dtype=float)
    m = len(pvals)
    order = np.argsort(pvals)
    out = np.empty(m)
    running = 0.0
    for rank, idx in enumerate(order):
        adj = (m - rank) * pvals[idx]
        running = max(running, adj)
        out[idx] = min(1.0, running)
    return out


def paired_stats(a, b, alternative="greater"):
    a = np.asarray(a, float)
    b = np.asarray(b, float)
    d = a - b
    n = len(d)
    mean = float(np.mean(d))
    sd = float(np.std(d, ddof=1)) if n > 1 else float("nan")
    se = sd / math.sqrt(n) if n > 1 and sd > 0 else 0.0
    if n > 1 and sd > 0:
        tcrit = stats.t.ppf(0.975, n - 1)
        ci = (mean - tcrit * se, mean + tcrit * se)
        t = mean / se
        p2 = 2 * stats.t.sf(abs(t), n - 1)
        if alternative == "greater":
            p = p2 / 2 if t >= 0 else 1 - p2 / 2
        elif alternative == "less":
            p = p2 / 2 if t <= 0 else 1 - p2 / 2
        else:
            p = p2
        dz = mean / sd
    else:
        ci = (mean, mean)
        t = float("inf") if mean > 0 else (-float("inf") if mean < 0 else 0.0)
        p = 0.0 if mean > 0 and alternative == "greater" else 1.0
        dz = float("inf") if mean > 0 else 0.0
    try:
        w = stats.wilcoxon(d, alternative=alternative, zero_method="wilcox")
        pw = float(w.pvalue)
    except Exception:
        pw = float("nan")
    nonzero = d[d != 0]
    if len(nonzero):
        signp = float(stats.binomtest(int(np.sum(nonzero > 0)), len(nonzero), .5,
                                     alternative=alternative).pvalue)
    else:
        signp = 1.0
    return {
        "n": n,
        "mean_diff": mean,
        "ci_low": ci[0],
        "ci_high": ci[1],
        "t": float(t),
        "p_one_sided": float(p),
        "cohen_dz": float(dz),
        "wilcoxon_p": pw,
        "sign_test_p": signp,
        "wins": int(np.sum(d > 0)),
        "ties": int(np.sum(d == 0)),
        "losses": int(np.sum(d < 0)),
    }


