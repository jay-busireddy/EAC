#!/usr/bin/env python
"""
EAC Study 2: pretrained-language-model validation with PEFT/LoRA.

Scientific purpose
------------------
This study addresses the main limitation of the synthetic EAC Study 1. It uses
an actual pretrained causal language model, freezes its base weights, learns an
initial task adapter from externally observed demonstrations, then ends the
external-observation phase. During the endogenous phase, novel candidate
problems are generated by an internal scheduler from already-seen symbol
vocabulary. The model proposes candidate answers. A deterministic executable
verifier returns pass/fail only; it never inserts a corrected answer when the
model failed to generate it. Accepted internally generated examples can then be
consolidated through LoRA.

Primary conditions
------------------
no_update                no endogenous update
replay                    literal replay of observed demonstrations
unchecked                 self-training on the model's own pseudo-labels
validated                 uniform endogenous recombination + executable verifier
hard_validated            uncertainty-targeted endogenous practice + verifier
dream_validated           cross-context recombination + verifier
hard_validated_anchor     hard_validated plus old-task anchor replay

Primary hypotheses are frozen in STUDY2_CONFIRMATORY_PROTOCOL.md.

The task is deliberately small enough for a laptop. It is still synthetic at the
problem level, but unlike Study 1 the learner is a pretrained Transformer with
real PEFT/LoRA attention-layer updates. Results therefore address model-scale
construct validity, not ecological validity on open-ended language tasks.
"""

